#!/usr/bin/env python3
"""Generates Utilities/XMPPStringPrepTables.h from the tables in RFC 3454.

Usage: Scripts/stringprep_tables.py rfc3454.txt Utilities/XMPPStringPrepTables.h

Download rfc3454.txt from https://www.rfc-editor.org/rfc/rfc3454.txt.
"""

import hashlib
import re
import sys

RFC_SHA256 = "eb722fa698fb7e8823b835d9fd263e4cdb8f1c7b0d234edf7f0e3bd2ccbb2c79"

RANGE_TABLES = [
    ("A.1", "A1", "Unassigned code points in Unicode 3.2"),
    ("B.1", "B1", "Commonly mapped to nothing"),
    ("C.1.1", "C11", "ASCII space characters"),
    ("C.1.2", "C12", "Non-ASCII space characters"),
    ("C.2.1", "C21", "ASCII control characters"),
    ("C.2.2", "C22", "Non-ASCII control characters"),
    ("C.3", "C3", "Private use"),
    ("C.4", "C4", "Non-character code points"),
    ("C.5", "C5", "Surrogate codes"),
    ("C.6", "C6", "Inappropriate for plain text"),
    ("C.7", "C7", "Inappropriate for canonical representation"),
    ("C.8", "C8", "Change display properties or are deprecated"),
    ("C.9", "C9", "Tagging characters"),
    ("D.1", "D1", "Characters with bidirectional property \"R\" or \"AL\""),
    ("D.2", "D2", "Characters with bidirectional property \"L\""),
]

ENTRY = re.compile(r"^   ([0-9A-F]{4,6})(?:-([0-9A-F]{4,6}))?(?:;(.*))?$")


def read_tables(text):
    tables = {}
    for match in re.finditer(r"----- Start Table (\S+) -----\n(.*?)----- End Table \1 -----", text, re.S):
        tables[match.group(1)] = [ENTRY.match(line) for line in match.group(2).splitlines() if ENTRY.match(line)]
    return tables


def ranges(entries):
    result = [(int(e.group(1), 16), int(e.group(2) or e.group(1), 16)) for e in entries]
    for (_, previous_last), (first, last) in zip(result, result[1:]):
        assert previous_last < first <= last, f"unsorted or overlapping at {first:04X}"
    return result


def mappings(entries):
    result = []
    for entry in entries:
        targets = entry.group(3).split(";")[0].split()
        result.append((int(entry.group(1), 16), [int(t, 16) for t in targets]))
    codes = [code for code, _ in result]
    assert codes == sorted(set(codes)), "unsorted or duplicate mappings"
    assert all(len(targets) <= 4 for _, targets in result)
    return result


def copyright_statement(text):
    statement = text.split("Full Copyright Statement\n", 1)[1].split("Acknowledgement\n", 1)[0]
    return [line.strip() for line in statement.strip().splitlines()]


def generate(text):
    tables = read_tables(text)
    out = [
        "//",
        "//  XMPPStringPrepTables.h",
        "//  XMPPFramework",
        "//",
        "//  Generated by Scripts/stringprep_tables.py from RFC 3454. Don't edit.",
        "//",
        "//  RFC 3454, Preparation of Internationalized Strings (\"stringprep\"):",
        "//",
    ]
    out += [f"//  {line}".rstrip() for line in copyright_statement(text)]
    out += [
        "//",
        "",
        "#import <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t first;",
        "    uint32_t last;",
        "} XMPPStringPrepRange;",
        "",
        "typedef struct {",
        "    uint32_t codePoint;",
        "    uint32_t length;",
        "    uint32_t mapping[4];",
        "} XMPPStringPrepMapping;",
    ]
    for table, name, title in RANGE_TABLES:
        entries = [f"{{0x{first:04X}, 0x{last:04X}}}" for first, last in ranges(tables[table])]
        out += ["", f"// {table} {title}", f"static const XMPPStringPrepRange XMPPStringPrepTable{name}[] = {{"]
        out += ["    " + ", ".join(entries[i:i + 4]) + "," for i in range(0, len(entries), 4)]
        out += ["};"]
    entries = []
    for code, targets in mappings(tables["B.2"]):
        mapping = ", ".join(f"0x{t:04X}" for t in targets)
        entries.append(f"{{0x{code:04X}, {len(targets)}, {{{mapping}}}}}")
    out += ["", "// B.2 Mapping for case-folding used with NFKC",
            "static const XMPPStringPrepMapping XMPPStringPrepTableB2[] = {"]
    out += ["    " + ", ".join(entries[i:i + 3]) + "," for i in range(0, len(entries), 3)]
    out += ["};", ""]
    return "\n".join(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip())
    with open(sys.argv[1], "rb") as file:
        data = file.read()
    if hashlib.sha256(data).hexdigest() != RFC_SHA256:
        sys.exit(f"{sys.argv[1]} isn't the RFC 3454 text this script was written for.")
    with open(sys.argv[2], "w") as file:
        file.write(generate(data.decode("ascii")))


if __name__ == "__main__":
    main()
